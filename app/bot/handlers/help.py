from aiogram import F, Router
from aiogram.filters import Command
from aiogram.fsm.context import FSMContext
from aiogram.types import Message

from app.bot.keyboards import BTN_HELP

router = Router(name="help")

HELP = (
    "❓ <b>Помощь</b>\n\n"
    "<b>Как пользоваться</b>\n"
    "1. «⚙️ Настройки фильтров» → «➕ Новый фильтр» и задайте параметры: коллекция, модель, фон, символ, "
    "цена в Stars или TON, редкость. Пустой параметр = любое значение.\n"
    "2. Когда на рынке появится подходящий лот, я пришлю уведомление с картинкой и кнопками покупки.\n"
    "3. «🎁 Найти подарки» показывает подходящие лоты, которые уже продаются (сначала дешёвые).\n"
    "4. «🔔 Мои уведомления» включает и выключает рассылку и отдельные фильтры.\n"
    "5. Если у бота включено мини-приложение (кнопка «📱 Мини-приложение» или кнопка меню у поля ввода), "
    "там всё то же с картинками, поиском и сортировкой.\n\n"
    "<b>Важно знать</b>\n"
    "• Я проверяю рынок по расписанию, поэтому уведомления приходят с задержкой "
    "в минуты, а не мгновенно, и покрывают самые свежие лоты каждой коллекции.\n"
    "• Названия сравниваются без учёта регистра, но должны совпадать полностью.\n"
    "• Цена в Stars относится к лотам в Stars (Telegram), цена в TON к лотам в TON (MRKT). "
    "Если задана цена только в одной валюте, лоты в другой под фильтр не попадут.\n"
    "• Редкость задаётся в процентах: <code>2%</code> = признак есть не больше чем у 2% подарков коллекции.\n"
    "• Владелец показывается, только если у него есть публичный @username.\n"
    "• Я не провожу сделки и никогда не прошу коды входа или пароли: покупка выполняется в Telegram "
    "по ссылке на подарок. Проверяйте цену и наличие на странице подарка.\n\n"
    "Команды: /start (главное меню), /help, /cancel (отменить ввод)"
)


@router.message(F.text == BTN_HELP)
@router.message(Command("help"))
async def help_(message: Message, state: FSMContext) -> None:
    await state.clear()
    await message.answer(HELP)
