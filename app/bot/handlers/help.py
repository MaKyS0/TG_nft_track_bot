from aiogram import F, Router
from aiogram.filters import Command
from aiogram.fsm.context import FSMContext
from aiogram.types import Message

from app.bot.keyboards import BTN_HELP

router = Router(name="help")

HELP = (
    "❓ <b>Помощь</b>\n\n"
    "<b>Как пользоваться</b>\n"
    "1. «⚙️ Настройки фильтров» → «➕ Новый фильтр», задайте нужные параметры "
    "(коллекция, модель, фон, символ, цена в Stars, редкость). Пустое поле = любое значение.\n"
    "2. Бот сам пришлёт уведомление, когда на рынке появится подходящее предложение.\n"
    "3. «🎁 Найти подарки» показывает уже известные подходящие предложения (сначала дешёвые).\n"
    "4. «🔔 Мои уведомления» — включить или выключить рассылку и фильтры.\n\n"
    "<b>Важно знать</b>\n"
    "• Бот проверяет рынок по расписанию, поэтому уведомления приходят с задержкой "
    "в минуты, а не мгновенно, и покрывают самые свежие лоты каждой коллекции.\n"
    "• Названия сравниваются без учёта регистра, но должны совпадать полностью.\n"
    "• Фильтры по цене работают для предложений в Stars; лоты в TON под ценовые фильтры не попадают.\n"
    "• Владелец показывается только если у него есть публичный @username.\n"
    "• Бот не проводит сделки и не просит коды входа или пароли — покупка выполняется в Telegram "
    "по ссылке на подарок. Проверяйте цену и наличие на странице подарка.\n\n"
    "Команды: /start, /cancel"
)


@router.message(F.text == BTN_HELP)
@router.message(Command("help"))
async def help_(message: Message, state: FSMContext) -> None:
    await state.clear()
    await message.answer(HELP)
